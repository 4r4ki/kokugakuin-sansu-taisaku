  function clockSim() {
    var ns = "http://www.w3.org/2000/svg";
    var hour = 3, minute = 0;
    var root = document.createElement("div");
    root.className = "sim";

    var hours = document.createElement("div");
    hours.className = "filter";
    var face = document.createElementNS(ns, "svg");
    face.setAttribute("viewBox", "0 0 220 220");
    face.setAttribute("class", "clock");
    var slider = document.createElement("input");
    slider.type = "range";
    slider.min = "0";
    slider.max = "59.9";
    slider.step = "0.1";
    slider.value = "0";
    slider.className = "clock-slider";
    slider.setAttribute("aria-label", "分");
    var info = document.createElement("p");
    info.className = "sim-info";

    function add(tag, attrs, txt) {
      var e = document.createElementNS(ns, tag);
      Object.keys(attrs).forEach(function (k) { e.setAttribute(k, attrs[k]); });
      if (txt != null) e.textContent = txt;
      face.appendChild(e);
      return e;
    }
    function hand(angle, len, cls) {
      var r = (angle - 90) * Math.PI / 180;
      add("line", { x1: 110, y1: 110, x2: 110 + len * Math.cos(r), y2: 110 + len * Math.sin(r), class: cls });
    }

    function draw() {
      while (face.firstChild) face.removeChild(face.firstChild);
      add("circle", { cx: 110, cy: 110, r: 100, class: "face" });
      for (var i = 1; i <= 12; i++) {
        var r = (i * 30 - 90) * Math.PI / 180;
        add("text", { x: 110 + 82 * Math.cos(r), y: 110 + 82 * Math.sin(r) + 5, class: "num" }, String(i));
      }
      for (var k = 0; k < 60; k++) {
        var a = (k * 6 - 90) * Math.PI / 180, inner = k % 5 ? 95 : 90;
        add("line", { x1: 110 + inner * Math.cos(a), y1: 110 + inner * Math.sin(a), x2: 110 + 100 * Math.cos(a), y2: 110 + 100 * Math.sin(a), class: "tick" });
      }
      var hAng = hour * 30 + minute * 0.5, mAng = minute * 6;
      hand(hAng, 52, "hour");
      hand(mAng, 78, "minute");
      add("circle", { cx: 110, cy: 110, r: 4, class: "pin" });

      var diff = Math.abs(hAng - mAng) % 360;
      if (diff > 180) diff = 360 - diff;
      var m = Math.round(minute * 10) / 10;
      info.innerHTML = hour + "時" + m + "分　短針 " + hour + "×30＋" + m + "×0.5 ＝ " + (Math.round(hAng * 100) / 100) +
        "°、長針 " + m + "×6 ＝ " + (Math.round(mAng * 100) / 100) + "°<br>2本の針の間の角：<b>" + (Math.round(diff * 100) / 100) + "°</b>";
    }

    for (var h = 1; h <= 11; h++) {
      (function (h) {
        var b = document.createElement("button");
        b.className = "chip" + (h === hour ? " active" : "");
        b.textContent = h + "時";
        b.addEventListener("click", function () {
          hour = h;
          Array.prototype.forEach.call(hours.children, function (c, i) { c.classList.toggle("active", i + 1 === hour); });
          draw();
        });
        hours.appendChild(b);
      })(h);
    }
    slider.addEventListener("input", function () {
      minute = parseFloat(slider.value);
      draw();
    });

    root.appendChild(hours);
    root.appendChild(face);
    root.appendChild(slider);
    root.appendChild(info);
    draw();
    return root;
  }

  window.GUIDE_WIDGETS.clockSim = clockSim;

