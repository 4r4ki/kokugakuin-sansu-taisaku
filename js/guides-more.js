  function svg(w, h, body) {
    return '<svg viewBox="0 0 ' + w + " " + h + '" xmlns="http://www.w3.org/2000/svg">' + body + "</svg>";
  }
  function line(x1, y1, x2, y2, cls) {
    return '<line x1="' + x1 + '" y1="' + y1 + '" x2="' + x2 + '" y2="' + y2 + '" class="' + (cls || "ln") + '"/>';
  }
  function rect(x, y, w, h, cls) {
    return '<rect x="' + x + '" y="' + y + '" width="' + w + '" height="' + h + '" class="' + (cls || "ln") + '"/>';
  }
  function poly(pts, cls) {
    return '<polygon points="' + pts.map(function (p) { return p.join(","); }).join(" ") + '" class="' + (cls || "ln") + '"/>';
  }
  function text(x, y, s, cls, anchor) {
    return '<text x="' + x + '" y="' + y + '"' + (cls ? ' class="' + cls + '"' : "") +
      (anchor ? ' style="text-anchor: ' + anchor + '"' : "") + ">" + s + "</text>";
  }
  function arc(cx, cy, r, a1, a2) {
    // a1 → a2（度、数学の向き）。y は下向きなので sin をひっくり返す
    var p = function (a) { return [cx + r * Math.cos(a * Math.PI / 180), cy - r * Math.sin(a * Math.PI / 180)]; };
    var s = p(a1), e = p(a2);
    return '<path d="M' + s[0].toFixed(1) + "," + s[1].toFixed(1) + " A" + r + "," + r + " 0 0,0 " + e[0].toFixed(1) + "," + e[1].toFixed(1) + '" class="mark"/>';
  }
  function tree(x, y) {
    return '<circle cx="' + x + '" cy="' + (y - 10) + '" r="7" class="shade"/>' + line(x, y - 3, x, y + 4);
  }

